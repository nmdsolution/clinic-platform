interface I18nPartage {
  addResourceBundle: (lng: string, ns: string, ressources: object, deep?: boolean, overwrite?: boolean) => void;
  hasResourceBundle: (lng: string, ns: string) => boolean;
  on: (evenement: string, rappel: (lng: string | Array<string>, ns: string) => void) => void;
}

/**
 * Applique les surcharges à l'instance i18next partagée de l'application (window.i18next).
 *
 * Important : on n'ajoute PAS les textes d'avance. i18next considère un module comme « chargé » dès
 * qu'un bundle existe pour lui et sauterait alors le vrai fr.json du module. On attend donc que le
 * bundle officiel du module soit ajouté (événement « added »), puis on superpose nos textes
 * (overwrite = true). Les modules déjà chargés au moment du démarrage sont traités immédiatement.
 */
export function appliquerSurchargesFr(): void {
  const i18n = (window as unknown as { i18next?: I18nPartage }).i18next;
  if (!i18n?.addResourceBundle || !i18n.on || !i18n.hasResourceBundle) {
    return;
  }
  let enCours = false;
  const superposer = (namespace: string) => {
    const textes = surchargesFr[namespace];
    if (!textes || enCours) {
      return;
    }
    enCours = true;
    try {
      i18n.addResourceBundle('fr', namespace, textes, true, true);
    } finally {
      enCours = false;
    }
  };

  i18n.on('added', (lng, namespace) => {
    const langue = Array.isArray(lng) ? lng[0] : lng;
    if (langue === 'fr') {
      superposer(namespace);
    }
  });
  Object.keys(surchargesFr).forEach((namespace) => {
    if (i18n.hasResourceBundle('fr', namespace)) {
      superposer(namespace);
    }
  });
}
